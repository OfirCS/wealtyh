import { parsePathfinderResult, applyPostParseGuardrails } from '@/lib/pathfinder-engine';
import { getCanadianRuleSet } from '@/lib/prompts';
import { SCENARIOS } from './scenarios';
import { scoreScenario, METRIC_NAMES, type MetricResult } from './metrics';

export interface ScenarioReport {
  id: string;
  description: string;
  metrics: MetricResult[];
  passed: boolean;
}

export interface Scorecard {
  scenarios: ScenarioReport[];
  perMetric: Record<string, { passed: number; total: number }>;
  totalPassed: number;
  totalScenarios: number;
  allPassed: boolean;
}

/**
 * Replays every recorded scenario through the REAL deterministic pipeline
 * (parse -> guardrails) — no live model calls, so it runs in CI without keys —
 * and scores the output against the independent metrics.
 */
export function runEvals(): Scorecard {
  const scenarios: ScenarioReport[] = [];
  const perMetric: Record<string, { passed: number; total: number }> = {};
  for (const name of METRIC_NAMES) perMetric[name] = { passed: 0, total: 0 };

  for (const scenario of SCENARIOS) {
    const parsed = parsePathfinderResult(scenario.rawAiResponse);
    const removedActions: string[] = [];
    const result = applyPostParseGuardrails(
      parsed,
      scenario.profile,
      scenario.customFunds,
      scenario.lifeEvent,
      getCanadianRuleSet(scenario.year),
      removedActions,
    );

    const metrics = scoreScenario(scenario, result, removedActions);
    const passed = metrics.every((m) => m.passed);
    for (const m of metrics) {
      perMetric[m.name].total += 1;
      if (m.passed) perMetric[m.name].passed += 1;
    }
    scenarios.push({ id: scenario.id, description: scenario.description, metrics, passed });
  }

  const totalPassed = scenarios.filter((s) => s.passed).length;
  return {
    scenarios,
    perMetric,
    totalPassed,
    totalScenarios: scenarios.length,
    allPassed: totalPassed === scenarios.length,
  };
}

/** Pretty per-metric rows for console.table. */
export function metricTable(card: Scorecard): Record<string, { pass: string; rate: string }> {
  const rows: Record<string, { pass: string; rate: string }> = {};
  for (const [name, { passed, total }] of Object.entries(card.perMetric)) {
    rows[name] = { pass: `${passed}/${total}`, rate: total ? `${Math.round((passed / total) * 100)}%` : 'n/a' };
  }
  return rows;
}

/** Render the committed scorecard markdown that the README links to. */
export function renderResultsMarkdown(card: Scorecard): string {
  const lines: string[] = [];
  lines.push('# Pathfinder eval scorecard');
  lines.push('');
  lines.push('_Generated by `npm run eval`. Replays recorded raw model responses through the real');
  lines.push('Router→Generate→Guardrails pipeline (no live API calls) and scores deterministic invariants._');
  lines.push('');
  lines.push(`**${card.totalPassed}/${card.totalScenarios} scenarios passing — ${card.allPassed ? 'all green ✅' : 'regressions ❌'}**`);
  lines.push('');
  lines.push('## By metric');
  lines.push('');
  lines.push('| Metric | Pass rate |');
  lines.push('| --- | --- |');
  for (const [name, { passed, total }] of Object.entries(card.perMetric)) {
    const rate = total ? Math.round((passed / total) * 100) : 0;
    lines.push(`| \`${name}\` | ${passed}/${total} (${rate}%) |`);
  }
  lines.push('');
  lines.push('## By scenario');
  lines.push('');
  lines.push('| Scenario | What it proves | Result |');
  lines.push('| --- | --- | --- |');
  for (const s of card.scenarios) {
    lines.push(`| \`${s.id}\` | ${s.description} | ${s.passed ? '✅' : '❌'} |`);
  }
  lines.push('');
  return lines.join('\n');
}
